#!/usr/bin/env python3
"""Export the unsearchable Mid AI model as C++17 constants in a .h file."""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np


MODEL_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(MODEL_DIR))
from neural_net import load_model  # noqa: E402


def cpp_float(value: float) -> str:
    number = float(value)
    if not math.isfinite(number):
        raise ValueError("model contains a non-finite weight or bias")
    literal = format(number, ".9g")
    if "." not in literal and "e" not in literal.lower():
        literal += ".0"
    return literal + "f"


def emit_float_array(name: str, array: np.ndarray) -> list[str]:
    values = np.asarray(array, dtype=np.float32).reshape(-1)
    lines = [f"inline constexpr float {name}[{values.size}] = {{"]
    for start in range(0, values.size, 6):
        chunk = values[start : start + 6]
        suffix = "," if start + 6 < values.size else ""
        lines.append("    " + ", ".join(cpp_float(value) for value in chunk) + suffix)
    lines.append("};")
    return lines


def export_header(output_path: Path) -> tuple[int, int]:
    model = load_model(MODEL_DIR)
    features = int(model["features"])
    hidden_sizes = [int(size) for size in model["hidden_sizes"]]
    outputs = [str(answer) for answer in model["outputs"]]
    weights = model["weights"]
    biases = model["biases"]
    layer_sizes = [features, *hidden_sizes, len(outputs)]

    if len(weights) != len(layer_sizes) - 1 or len(biases) != len(weights):
        raise ValueError("model layer count does not match its metadata")
    for index, (weight, bias) in enumerate(zip(weights, biases)):
        expected_weight_shape = (layer_sizes[index], layer_sizes[index + 1])
        expected_bias_shape = (layer_sizes[index + 1],)
        if weight.shape != expected_weight_shape or bias.shape != expected_bias_shape:
            raise ValueError(f"model layer {index} has a shape that does not match its metadata")

    layer_count = len(weights)
    lines = [
        "// Generated by model_to_header.py; edit the model or converter, not this file.",
        "#pragma once",
        "#include <cstddef>",
        "",
        "namespace mid_ai_unsearchable {",
        f"inline constexpr std::size_t kFeatureCount = {features};",
        f"inline constexpr std::size_t kOutputCount = {len(outputs)};",
        f"inline constexpr std::size_t kLayerCount = {layer_count};",
        f"inline constexpr std::size_t kParameterCount = {int(model['parameter_count'])};",
        f"inline constexpr std::size_t kTrainingEpochs = {int(model['epochs'])};",
        "inline constexpr std::size_t kLayerSizes[kLayerCount + 1] = {",
        "    " + ", ".join(str(size) for size in layer_sizes),
        "};",
        'inline constexpr char kFeatureHash[] = "BLAKE2b-64, little-endian modulo feature count";',
        'inline constexpr char kFeaturePipeline[] = "case-folded word, adjacent-word, and character 3/4-gram counts; L2 normalized";',
        "inline constexpr const char* kOutputs[kOutputCount] = {",
    ]
    lines.extend("    " + json.dumps(answer, ensure_ascii=False) + "," for answer in outputs)
    lines.append("};")

    for index, (weight, bias) in enumerate(zip(weights, biases)):
        lines.append("")
        lines.extend(emit_float_array(f"kWeights{index}", weight))
        lines.extend(emit_float_array(f"kBiases{index}", bias))

    lines.extend(["", "}  // namespace mid_ai_unsearchable", ""])
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return int(model["parameter_count"]), len(outputs)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "output",
        nargs="?",
        type=Path,
        default=Path(__file__).with_name("model_data.h"),
        help="header output path (default: model_data.h beside this script)",
    )
    args = parser.parse_args()
    output_path = args.output.resolve()
    try:
        parameters, output_count = export_header(output_path)
    except (FileNotFoundError, OSError, ValueError, KeyError) as error:
        parser.error(str(error))
    print(f"Wrote {output_path} ({parameters:,} parameters, {output_count} responses).")


if __name__ == "__main__":
    main()
